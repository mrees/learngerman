export const wordById = new Map(words.map((w) => [w.id, w]));
export const sentenceById = new Map(sentences.map((s) => [s.id, s]));
export const unitById = new Map(units.map((u) => [u.id, u]));

export function wordsInUnit(unitId: string): Word[] {
  return words.filter((w) => w.unit === unitId);
}

export function sentencesInUnit(unitId: string): Sentence[] {
  return sentences.filter((s) => s.unit === unitId);
}

export function gloss(word: Word): string {
  if (word.article) return `${word.article} ${word.de}`;
  return word.de;
}

export function genderLabel(word: Word): string | null {
  if (word.number === "plural") return "plural";
  if (word.article === "der") return "masculine";
  if (word.article === "die") return "feminine";
  if (word.article === "das") return "neuter";
  return null;
}

export function wordBlob(word: Word): string {
  return normalizeAnswer(
    [word.de, word.article, word.plural, word.en, word.exampleDe, word.exampleEn, word.tip, word.forms, gloss(word)]
      .filter(Boolean)
      .join(" "),
  );
}

function validateCurriculum(): void {
  const errors: string[] = [];
  const wordIds = new Set<string>();
  for (const word of words) {
    if (wordIds.has(word.id)) errors.push(`Duplicate word id ${word.id}`);
    wordIds.add(word.id);
    if (!unitById.has(word.unit)) errors.push(`Word ${word.id} has unknown unit`);
    if (word.article && word.pos !== "noun") errors.push(`Non-noun has article: ${word.id}`);
  }
  const sentenceIds = new Set<string>();
  for (const sentence of sentences) {
    if (sentenceIds.has(sentence.id)) errors.push(`Duplicate sentence id ${sentence.id}`);
    sentenceIds.add(sentence.id);
    if (!unitById.has(sentence.unit)) errors.push(`Sentence ${sentence.id} has unknown unit`);
    const joined = normalizeAnswer(sentence.tokens.join(" "));
    const canonical = normalizeAnswer(sentence.de);
    if (joined !== canonical) {
      errors.push(`Tokens for ${sentence.id} do not match: ${sentence.tokens.join(" ")} vs ${sentence.de}`);
    }
    for (const distractor of sentence.distractors) {
      if (sentence.tokens.some((token) => normalizeAnswer(token) === normalizeAnswer(distractor))) {
        errors.push(`Distractor “${distractor}” duplicates a token in ${sentence.id}`);
      }
    }
  }
  if (errors.length) throw new Error(errors.join("\n"));
}

validateCurriculum();
